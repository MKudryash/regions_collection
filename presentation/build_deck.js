// pptxgenjs не записывает цвета и шрифты темы и вставляет лишний <a:pPr> между фрагментами одного абзаца
// (он отменяет маркер списка). Обе правки делаются в zip-архиве средствами Python (стандартная библиотека).
function postprocess(file, theme) {
  const py = `
import json, re, sys, zipfile, shutil
src, theme = sys.argv[1], json.loads(sys.argv[2]); tmp = src + ".tmp"
pat = re.compile(r"</a:r><a:pPr\\b[^>]*?(?:/>|>.*?</a:pPr>)")
def fix_theme(xml):
    name = theme["name"].replace("&", "&amp;")
    for tag in ("a:theme", "a:clrScheme", "a:fontScheme"):
        xml = re.sub(r"(<" + tag + r"\\b[^>]*?\\bname=\\")[^\\"]*", lambda m: m.group(1) + name, xml, count=1)
    for key, val in theme["colors"].items():
        xml = re.sub(r"<a:" + key + r">.*?</a:" + key + r">", '<a:' + key + '><a:srgbClr val="' + val + '"/></a:' + key + '>', xml, count=1, flags=re.S)
    xml = re.sub(r'(<a:majorFont><a:latin typeface=")[^"]*', lambda m: m.group(1) + theme["headFontFace"], xml, count=1)
    xml = re.sub(r'(<a:minorFont><a:latin typeface=")[^"]*', lambda m: m.group(1) + theme["bodyFontFace"], xml, count=1)
    return xml
with zipfile.ZipFile(src) as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
    for item in zin.infolist():
        data = zin.read(item.filename)
        if re.match(r"ppt/slides/slide\\d+\\.xml$", item.filename):
            data = pat.sub("</a:r>", data.decode("utf-8")).encode("utf-8")
        elif re.match(r"ppt/theme/theme\\d+\\.xml$", item.filename):
            data = fix_theme(data.decode("utf-8")).encode("utf-8")
        zout.writestr(item, data)
shutil.move(tmp, src)
`;
  require("child_process").execFileSync("python3", ["-c", py, file, JSON.stringify(theme)], { stdio: "inherit" });
}

